export type Copy = {
  [K in keyof typeof en]: (typeof en)[K] extends string ? string : (typeof en)[K];
};

const PACK: Record<UiLang, Copy> = { en, zh };

export function t(lang: UiLang | undefined | null): Copy {
  return PACK[lang === "zh" ? "zh" : "en"];
}

export function statusLabel(c: Copy, status: string): string {
  if (status.startsWith("modelFailed:")) {
    return c.modelFailed(Number(status.slice("modelFailed:".length)) || 0);
  }
  const table = c as unknown as Record<string, unknown>;
  const value = table[status];
  return typeof value === "string" ? value : status;
}

export function applyUiLang<
  T extends { uiLang?: UiLang; speechLang: "zh-CN" | "en-US"; systemPrompt: string },
>(prefs: T, uiLang: UiLang): T {
  return {
    ...prefs,
    uiLang,
    speechLang: uiLang === "zh" ? "zh-CN" : "en-US",
    systemPrompt: isDefaultPrompt(prefs.systemPrompt) ? promptFor(uiLang) : prefs.systemPrompt,
  };
}

export function isDefaultPrompt(value: string): boolean {
  const trimmed = value.trim();
  return (
    !trimmed ||
    trimmed === SYSTEM_PROMPT.en ||
    trimmed === SYSTEM_PROMPT.zh ||
    LEGACY_SYSTEM_PROMPTS.includes(trimmed)
  );
}

export function promptFor(lang: UiLang): string {
  return SYSTEM_PROMPT[lang];
}

